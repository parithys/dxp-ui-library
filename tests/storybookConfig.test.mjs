// Library Storybook guards that need no Storybook install (plain node:test): the configuration is in place (framework, docs and a11y addons, autodocs,
// Tailwind v4), it stays out of the package build, and every story is a story OF the library (its own sources, no application imports, no copied styling).
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { storyFiles } from '../scripts/storybook-coverage.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');
const CATEGORIES = ['Foundations', 'Primitives', 'Forms', 'Navigation', 'Feedback & Status'];
// A composite page (one form built from several components) has no single `component`; its docs page is still generated by autodocs.
const COMPOSITE = ['stories/forms/Validation.stories.tsx'];
const stories = () => storyFiles().filter((f) => /\.stories\.tsx$/.test(f));

test('Storybook is configured: scripts, dev dependencies, framework, docs and a11y addons, Tailwind v4', () => {
  const pkg = JSON.parse(read('package.json'));
  for (const s of ['storybook', 'build-storybook']) assert.ok(pkg.scripts[s], `script ${s}`);
  for (const d of ['storybook', '@storybook/react-vite', '@storybook/addon-docs', '@storybook/addon-a11y', '@tailwindcss/vite']) assert.ok(pkg.devDependencies[d], `devDependency ${d}`);
  assert.ok(!Object.keys(pkg.dependencies ?? {}).some((d) => /storybook/.test(d)), 'no Storybook package is a runtime dependency');
  for (const f of ['.storybook/main.ts', '.storybook/preview.tsx', '.storybook/manager.ts', '.storybook/storybook.css', 'stories/CONVENTIONS.md', 'stories/README.md']) assert.ok(fs.existsSync(path.join(ROOT, f)), f);
  const main = read('.storybook/main.ts');
  assert.match(main, /@storybook\/react-vite/);
  assert.match(main, /addons:\s*\[[^\]]*'@storybook\/addon-docs'[^\]]*\]/);
  assert.match(main, /addons:\s*\[[^\]]*'@storybook\/addon-a11y'[^\]]*\]/, 'the a11y addon is enabled');
  assert.match(main, /@tailwindcss\/vite/);
  assert.match(main, /stories\/\*\*\/\*\.stories/);
});

test('the preview loads the library\'s own CSS and enables autodocs and the a11y checks for every story', () => {
  const preview = read('.storybook/preview.tsx');
  assert.match(preview, /tags:\s*\[\s*'autodocs'\s*\]/, 'autodocs for every story file by default');
  assert.match(preview, /a11y:\s*\{/, 'the a11y parameters are set');
  assert.match(preview, /import '\.\/storybook\.css'/);
  const css = read('.storybook/storybook.css');
  for (const part of ['src/styles/preset.css', 'src/styles/components.css', 'tooltip.css']) assert.ok(css.includes(part), `storybook.css imports ${part}`);
  assert.ok(!/\{[^}]*:[^}]*\}/.test(css.replace(/\/\*[\s\S]*?\*\//g, '')), 'storybook.css declares no rule of its own');
});

test('Storybook stays out of the package: its build is not part of dist, lint ignores only its output', () => {
  const pkg = JSON.parse(read('package.json'));
  assert.ok(!pkg.files.some((f) => /stories|storybook/.test(f)), 'stories are not published');
  assert.match(read('.gitignore'), /^storybook-static$/m);
  assert.match(read('tsconfig.json'), /"stories"/, 'tsc type-checks the stories');
  assert.deepEqual(JSON.parse(read('tsconfig.build.json')).include, ['src'], 'the type build covers src only');
});

test('every story file uses autodocs (a `component` in its meta, no `autodocs: false`), a known category and the library\'s own sources', () => {
  const files = stories();
  assert.ok(files.length >= 40, `${files.length} story files`);
  const problems = [];
  for (const f of files) {
    const text = read(f);
    const title = /(?:const meta\b[^=]*=|export default)\s*\{\s*title: '([^']+)'/.exec(text)?.[1];
    if (!title || !CATEGORIES.includes(title.split('/')[0])) problems.push(`${f}: title ${title}`);
    // Foundations pages may show tokens and classes with no component; every other page documents a component (autodocs builds its page from `component`).
    if (!f.startsWith('stories/foundations/') && !COMPOSITE.includes(f) && !/\n\s*component:/.test(text)) problems.push(`${f}: meta has no \`component\``);
    if (/tags:\s*\[[^\]]*'!autodocs'/.test(text)) problems.push(`${f}: opts out of autodocs`);
    if (/from '(\.\.\/)+prototype|from '@\/|from '@vfq\/dxp-ui'|from 'next\//.test(text)) problems.push(`${f}: imports the application or the package itself`);
    if (/console\.log/.test(text)) problems.push(`${f}: console.log`);
    if (/#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b|rgba?\(/.test(text.replace(/href=['"]#[^'"]*['"]/g, ''))) problems.push(`${f}: literal colour`);
    if (/@storybook\/react['"]/.test(text)) problems.push(`${f}: import from @storybook/react-vite instead`);
    for (const m of text.matchAll(/from '(\.\.?\/[^']+)'/g)) {
      const target = path.resolve(path.dirname(path.join(ROOT, f)), m[1]);
      if (!target.startsWith(ROOT + path.sep)) problems.push(`${f}: ${m[1]} leaves the package`);
    }
  }
  assert.deepEqual(problems, []);
});

test('Storybook has no stylesheet of its own: no CSS files under stories/, no <style> or injected rules', () => {
  const all = [];
  (function walk(d) {
    for (const f of fs.readdirSync(d)) {
      const p = path.join(d, f);
      if (fs.statSync(p).isDirectory()) walk(p);
      else all.push(p);
    }
  })(path.join(ROOT, 'stories'));
  assert.deepEqual(all.filter((f) => /\.css$/.test(f)).map((f) => path.relative(ROOT, f)), []);
  const offenders = all.filter((f) => /\.(tsx?|mdx)$/.test(f) && /<style[ >]|insertRule|createElement\('style'\)/.test(fs.readFileSync(f, 'utf8'))).map((f) => path.relative(ROOT, f));
  assert.deepEqual(offenders, []);
});
